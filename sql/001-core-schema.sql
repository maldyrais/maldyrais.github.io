create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name_id text not null,
  name_en text not null,
  name_ja text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.works (
  id bigint generated by default as identity primary key,
  title_id text not null,
  title_en text,
  title_ja text,
  description_id text,
  description_en text,
  description_ja text,
  category_id bigint references public.categories(id) on update cascade on delete restrict,
  project_start_date date,
  project_end_date date,
  project_sort_date date not null default current_date,
  image_path text,
  image_url text,
  tools text[] default '{}',
  show_on_home boolean not null default false,
  home_order integer,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint works_valid_project_dates check (
    project_end_date is null
    or project_start_date is null
    or project_end_date >= project_start_date
  ),
  constraint works_has_image check (
    image_url is not null or image_path is not null
  )
);

