create or replace function public.sync_work_sort_date()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.project_sort_date := coalesce(
    new.project_end_date,
    new.project_start_date,
    (new.created_at at time zone 'UTC')::date,
    current_date
  );
  return new;
end;
$$;

create or replace function public.set_work_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_works_sync_sort_date on public.works;
create trigger trg_works_sync_sort_date
before insert or update of project_start_date, project_end_date, created_at
on public.works
for each row execute function public.sync_work_sort_date();

drop trigger if exists trg_works_updated_at on public.works;
create trigger trg_works_updated_at
before update on public.works
for each row execute function public.set_work_updated_at();

create index if not exists works_home_index
on public.works (home_order)
where is_published = true and show_on_home = true;

create index if not exists works_date_index
on public.works (project_sort_date desc)
where is_published = true;

create index if not exists works_category_date_index
on public.works (category_id, project_sort_date desc)
where is_published = true;

alter table public.categories enable row level security;
alter table public.works enable row level security;

drop policy if exists "Public can read categories" on public.categories;
create policy "Public can read categories"
on public.categories for select
to anon, authenticated
using (is_active = true);

drop policy if exists "Public can read published works" on public.works;
create policy "Public can read published works"
on public.works for select
to anon, authenticated
using (is_published = true);
